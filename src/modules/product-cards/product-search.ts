export interface ProductSearch {
  /**
   * Готовые строки для `to_tsquery`: оригинал и варианты в другой
   * письменности. Каждая уже собрана из префиксов и склеена через `&`.
   */
  queries: string[];
  /**
   * Тот же запрос для подстрочного сравнения с названием. Полнотекстовый
   * поиск сравнивает слова с начала, а модель ищут по хвосту артикула —
   * «4470» вместо «G4470». Экранирован для LIKE.
   *
   * `null` — запрос короче трёх символов, и подстроку искать нечем.
   */
  like: string | null;
}

/**
 * `null` — в запросе не осталось ни одного слова (например, ввели «???»).
 * Вызывающий решает, что показать: молча отдать весь каталог нельзя, иначе
 * человек решит, что нашлось всё подряд.
 */
export function buildProductSearch(raw: string): ProductSearch | null {
  const terms = tokenize(raw);
  if (terms.length === 0) return null;

  const queries = unique([
    toTsQuery(terms),
    toTsQuery(terms.map(transliterate(TO_CYRILLIC))),
    toTsQuery(terms.map(transliterate(TO_LATIN))),
  ]);

  const trimmed = raw.trim();
  const like =
    trimmed.length >= MIN_LIKE_LENGTH && trimmed.length <= MAX_LIKE_LENGTH
      ? `%${escapeLike(trimmed)}%`
      : null;

  return { queries, like };
}

/**
 * Слова из ввода. Всё, что не буква и не цифра, — разделитель: так из строки
 * заведомо исчезают операторы tsquery (`&`, `|`, `!`, `:`, скобки), на которых
 * `to_tsquery` иначе падает с синтаксической ошибкой прямо покупателю в лицо.
 */
function tokenize(raw: string): string[] {
  return raw
    .toLowerCase()
    .split(/[^\p{L}\p{N}]+/u)
    .filter(Boolean)
    .slice(0, MAX_TERMS)
    .map((term) => term.slice(0, MAX_TERM_LENGTH));
}

/** Все слова обязательны, каждое — префикс: «canon g24» найдёт «Canon G2470». */
function toTsQuery(terms: string[]): string {
  return terms.map((term) => `${term}:*`).join(' & ');
}

function transliterate(table: [string, string][]) {
  return (term: string): string => {
    let rest = term;
    let out = '';
    outer: while (rest.length > 0) {
      for (const [from, to] of table) {
        if (rest.startsWith(from)) {
          out += to;
          rest = rest.slice(from.length);
          continue outer;
        }
      }
      out += rest[0];
      rest = rest.slice(1);
    }
    return out;
  };
}

function unique(values: string[]): string[] {
  return [...new Set(values.filter(Boolean))];
}

/** `%` и `_` в вводе — это подстановочные знаки LIKE, а не то, что искал человек. */
function escapeLike(value: string): string {
  return value.replace(/[\\%_]/g, (ch) => `\\${ch}`);
}
