/**
 * Разбор поискового запроса покупателя.
 *
 * Что здесь важно понимать про сам поиск. Полнотекстовый индекс Postgres ищет
 * по *словам целиком*: запрос «клав» не найдёт «клавиатуру», потому что это
 * разные лексемы. Живой поиск в шапке при этом дописывает запрос по буквам, и
 * без префиксного совпадения выдача была бы пустой ровно до последней буквы
 * слова. Поэтому каждое слово превращается в префикс `слово:*`.
 *
 * Второе — три письменности на одной витрине. Интерфейс есть на русском,
 * узбекской латинице и узбекской кириллице, а названия товаров продавцы
 * заводят как придётся. Покупатель, набравший «printer», обязан находить
 * «принтер». Поэтому к запросу добавляются варианты в другой письменности:
 * это лишние совпадения, а не потерянные — ветки объединяются через OR.
 */

/** Больше слов в запросе — это уже не поиск, а вставленный абзац. */
const MAX_TERMS = 8;

/** Длиннее не бывает осмысленного слова, а лексема в Postgres обрезается на 2047 байтах. */
const MAX_TERM_LENGTH = 40;

/**
 * С какой длины запроса подключается поиск подстроки. Триграммный индекс
 * работает от трёх символов; на более коротком запросе он бесполезен, и
 * `ILIKE '%по%'` превратился бы в чтение всей таблицы — на каждой букве,
 * которую человек набирает в шапке.
 */
const MIN_LIKE_LENGTH = 3;

/**
 * И до какой. Подстрокой ищут артикул, а не абзац; на вставленной простыне
 * ветка `ILIKE '%…%'` только зря читала бы таблицу — полнотекстовые ветки с
 * такой строкой справятся сами.
 */
const MAX_LIKE_LENGTH = 100;

