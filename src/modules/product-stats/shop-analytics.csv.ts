/**
 * Сборка аналитики магазина в CSV.
 *
 * Чистая функция без Nest и без базы — её единственный вход целиком описан
 * `AnalyticsCsvInput`. Так она проверяется тестом напрямую: правила экранирования
 * ломаются на данных, которых в базе разработчика никогда нет («Ноутбук; б/у» с
 * переводом строки в описании), и ловить это поднятием приложения было бы
 * бессмысленно долго.
 *
 * Формат выбран под Excel в русской локали, а не под RFC 4180 в вакууме: файл
 * скачивает продавец и открывает двойным щелчком, а не разбирает скриптом.
 * Отсюда три решения, каждое из которых иначе даёт нечитаемый файл:
 *
 * 1. **Разделитель — точка с запятой.** Excel с русскими региональными
 *    настройками считает запятую десятичным знаком и складывает всю строку в
 *    одну ячейку. Точка с запятой — то, что этот же Excel сам пишет при
 *    сохранении в CSV.
 * 2. **BOM в начале.** Без него Excel читает файл в системной однобайтовой
 *    кодировке, и кириллица приезжает кракозябрами. Три байта в начале — цена
 *    того, чтобы продавец увидел «Ноутбук», а не «Ð�Ð¾ÑƒÑ‚Ð±ÑƒÐº».
 * 3. **Проценты целым числом, без знака `%` и без дробей.** Дробь пришлось бы
 *    писать либо через точку (Excel в русской локали прочтёт как текст), либо
 *    через запятую (совпадёт с разделителем полей — спасёт кавычка, но число
 *    станет заложником настроек машины). Целое число в столбце «Конверсия, %»
 *    однозначно на любой локали.
 *
 * Экранируются **все** значения, а не только подозрительные: в названии товара
 * продавец пишет что угодно, включая точку с запятой, кавычку и перевод строки,
 * а «поставим кавычки, только если надо» — это ещё одно условие, которое можно
 * ошибиться проверить. Кавычки вокруг чисел Excel снимает и распознаёт число
 * как число, так что цена единообразия нулевая.
 */

/** Разделитель полей. Точка с запятой — см. докблок файла. */
const SEP = ';';

/**
 * Конец строки — CRLF, как в RFC 4180 и как пишет сам Excel. Голый `\n` тоже
 * прочитается, но при открытии в блокноте Windows файл слипся бы в одну строку.
 */
const EOL = '\r\n';

/**
 * Метка порядка байтов: единственный способ объяснить Excel, что это UTF-8.
 * Записана escape-последовательностью намеренно — сам символ невидим, и в
 * исходнике его невозможно ни увидеть, ни отличить от случайно вставленного.
 */
const BOM = '\uFEFF';

/** Строка топа товаров в выгрузке. */
export interface AnalyticsCsvProduct {
  name: string;
  views: number;
  visits: number;
  contacts: number;
  contactVisitors: number;
  conversionPercent: number;
}

/** Сутки в выгрузке. */
export interface AnalyticsCsvDay {
  date: string;
  views: number;
  visitors: number;
  phoneClicks: number;
  telegramClicks: number;
  contactVisitors: number;
}

/**
 * Что нужно выгрузке — ровно подмножество `ShopAnalyticsDto`.
 *
 * Описано своим интерфейсом, а не типом DTO: DTO — это контракт HTTP со
 * свагерными декораторами, и тесту пришлось бы собирать все его поля, включая
 * не влияющие на файл. Структурная совместимость держит их вместе без импорта.
 */
export interface AnalyticsCsvInput {
  shopName: string;
  from: string;
  to: string;
  daily: AnalyticsCsvDay[];
  topProducts: AnalyticsCsvProduct[];
}

export function buildAnalyticsCsv(input: AnalyticsCsvInput): string {
  const lines: string[] = [
    row(['Магазин', input.shopName]),
    row(['Период', `${input.from} — ${input.to}`]),
    '',
    row(['По дням']),
    row([
      'Дата',
      'Просмотры',
      'Посетители',
      'Раскрытий телефона',
      'Переходов в Telegram',
      'Дошли до контакта',
    ]),
    ...input.daily.map((day) =>
      row([
        day.date,
        day.views,
        day.visitors,
        day.phoneClicks,
        day.telegramClicks,
        day.contactVisitors,
      ]),
    ),
    '',
    row(['Топ товаров']),
    row([
      'Товар',
      'Просмотры',
      'Посещения',
      'Контакты',
      'Дошли до контакта',
      'Конверсия, %',
    ]),
    ...input.topProducts.map((product) =>
      row([
        product.name,
        product.views,
        product.visits,
        product.contacts,
        product.contactVisitors,
        product.conversionPercent,
      ]),
    ),
  ];

  return BOM + lines.join(EOL) + EOL;
}

function row(cells: (string | number)[]): string {
  return cells.map(cell).join(SEP);
}

/**
 * Одно значение в кавычках.
 *
 * Внутренняя кавычка удваивается — это единственный способ её записать,
 * предусмотренный форматом. Перенос строки внутри значения приводится к `\n`:
 * иначе `\r\n` внутри названия товара записан теми же байтами, что и конец
 * строки файла, и разборщик, который читает построчно, а кавычки учитывает
 * потом (а так устроено большинство самописных), развалит таблицу на этом месте.
 */
function cell(value: string | number): string {
  const text =
    typeof value === 'number' ? String(value) : value.replace(/\r\n?/g, '\n');

  return `"${text.replace(/"/g, '""')}"`;
}
