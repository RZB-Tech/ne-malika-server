/**
 * Чистая половина счётчика поисковых запросов: пороги и нормализация строки.
 *
 * Вынесено из сервиса ради теста: нормализация — единственное место, где
 * решается, окажутся ли «Ноутбук  ASUS» и «ноутбук asus» одной строкой отчёта
 * или двумя, и проверяться это должно напрямую, без поднятия контейнера Nest
 * и без Redis. Ровно тем же соображением живёт `product-stats.util.ts`.
 */

/**
 * Ширина колонки `shop_search_hits_daily.query`. Число здесь не «на всякий
 * случай»: строка длиннее просто не запишется, и Postgres ответит ошибкой уже
 * после того, как поиск покупателю отдан. Обрезаем на входе.
 */
export const SEARCH_QUERY_MAX_LENGTH = 100;

/**
 * С какой длины запрос считается запросом.
 *
 * Поле в шапке шлёт запрос через 300 мс после последней буквы
 * (`components/shared/search-bar.tsx`), поэтому на пути к «ноутбуку» успевают
 * уйти и «но», и «ноу». Две буквы — заведомо промах: осмысленного запроса
 * такой длины у нас нет, а в отчёте они выглядели бы как самые популярные
 * слова площадки. Три — та же граница, с которой включается поиск подстроки
 * (`MIN_LIKE_LENGTH` в `product-search.ts`); держим их одинаковыми осознанно.
 *
 * Полностью дребезг это не убирает: «ноут» на пути к «ноутбуку» пройдёт порог
 * и запишется. Цена принята: убрать её можно только отдельным событием с
 * клиента «поиск завершён», а не запросом за списком товаров.
 */
export const SEARCH_QUERY_MIN_LENGTH = 3;

/**
 * Окно, в котором тот же посетитель с тем же запросом больше не считается.
 *
 * Десять минут закрывают F5, возврат «назад» из карточки товара и повторный
 * заход из истории браузера — всё, что для продавца является одним интересом,
 * а не десятью. Больше делать нельзя: человек, вернувшийся к тому же запросу
 * через час, ищет второй раз по-настоящему.
 */
export const SEARCH_DEDUP_WINDOW_SEC = 600;

/**
 * Сколько магазинов максимум засчитывает один поиск.
 *
 * Записываем не по отданной странице, а по всей выдаче: у магазина, чей товар
 * стоит на тридцатой позиции, запрос иначе не появился бы в отчёте вовсе —
 * хотя по этому запросу его находят. Но и «всей выдачей» может оказаться
 * половина площадки: запрос из одной частой буквосочетания совпадёт с тысячей
 * магазинов, и один поиск превратился бы в тысячу строк вставки.
 *
 * Двести — потолок, за которым отчёт всё равно перестаёт что-либо значить:
 * если вас нашли вместе с двумя сотнями других магазинов, это не «вас нашли по
 * запросу». Обрезка не упорядочена (см. `findMatchingShopIds`), и это честно:
 * выбрать «двести самых достойных» тут не по чему.
 */
export const SEARCH_HIT_SHOP_LIMIT = 200;

/**
 * Привести запрос к виду, в котором он хранится и показывается в отчёте.
 * `null` — записывать нечего: после нормализации осталось меньше порога.
 *
 * Порядок шагов важен. Схлопывание пробелов идёт до обрезки: иначе «ноутбук
 * ␣␣␣…␣␣ asus» отрезался бы по сотому пробелу и превратился в «ноутбук» с
 * хвостом из пустоты. Финальный `trim` — после обрезки: срез на сотом символе
 * может попасть ровно на пробел, и строка «ноутбук игровой ...␣» отличалась бы
 * от такой же без хвостового пробела, то есть заняла бы вторую строку отчёта.
 *
 * Регистр снимаем с явно указанной локалью, а не `toLowerCase()`: у метода без
 * локали поведение зависит от настроек процесса, и на машине с турецкой
 * локалью «I» превратилось бы в «ı» — запрос «IPhone» уехал бы в отдельную
 * строку отчёта. Русская локаль выбрана как язык большинства запросов; на
 * латинице и узбекской кириллице она работает как обычное приведение регистра.
 */
export function normalizeSearchQuery(raw: string): string | null {
  const normalized = raw
    .trim()
    .toLocaleLowerCase('ru')
    .replace(/\s+/g, ' ')
    .slice(0, SEARCH_QUERY_MAX_LENGTH)
    .trim();

  return normalized.length >= SEARCH_QUERY_MIN_LENGTH ? normalized : null;
}
