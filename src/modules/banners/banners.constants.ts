/**
 * Допустимые размеры картинки баннера. Проверку размеров делает браузер при
 * загрузке — здесь эти числа живут ради Swagger: клиент и админ должны видеть
 * одно и то же требование, а не два расходящихся списка в двух репозиториях.
 *
 * Первый в списке — основной: по нему карусель считает высоту слота.
 * Меняя их, поменяйте и `BANNER_FORMATS` в клиенте (`lib/api/banners.ts`).
 */
export const BANNER_FORMATS = [
  { width: 1942, height: 809 },
  { width: 1240, height: 400 },
] as const;

export const BANNER_FORMATS_LABEL = BANNER_FORMATS.map(
  (f) => `${f.width}×${f.height}`,
).join(' / ');

/** Сколько баннеров отдаём на витрину: карусель длиннее никто не долистывает. */
export const MAX_ACTIVE_BANNERS = 10;
