import { moderationStatusEnum } from '../../db/schema';

/**
 * Допустимые размеры картинки баннера. Проверку размеров делает браузер при
 * загрузке — здесь эти числа живут ради Swagger: клиент и админ должны видеть
 * одно и то же требование, а не два расходящихся списка в двух репозиториях.
 *
 * Первый в списке — основной: по нему карусель считает высоту слота.
 * Меняя их, поменяйте и `BANNER_FORMATS` в клиенте (`lib/api/banners.ts`).
 *
 * Сервер разрешение не проверяет вовсе — ни по этим числам, ни по каким-то
 * другим, — и это решение, а не забытая проверка. Прочитать размеры картинки
 * нечем: в зависимостях проекта нет ни одной библиотеки, разбирающей
 * изображения, а тянуть `sharp` (нативная сборка, десятки мегабайт в образе)
 * ради отсева кривого баннера дороже самого отсева. Продавец протолкнёт через
 * curl что угодно — и это ловит модерация, которая всё равно стоит на пути его
 * баннера. У администратора проверки нет и не нужно: его баннер публикуется
 * без чужого одобрения именно потому, что одобряет он сам.
 */
export const BANNER_FORMATS = [
  { width: 1942, height: 809 },
  { width: 1240, height: 400 },
] as const;

export const BANNER_FORMATS_LABEL = BANNER_FORMATS.map(
  (f) => `${f.width}×${f.height}`,
).join(' / ');

/** Сколько баннеров отдаём на витрину: карусель длиннее никто не долистывает. */
export const MAX_ACTIVE_BANNERS = 10;

/**
 * Сколько мест карусели отдано баннерам продавцов.
 *
 * С появлением платных баннеров `MAX_ACTIVE_BANNERS` перестал быть «сколько
 * долистают» и стал делёжкой дефицита: без явного резерва десяток подписчиков
 * молча вытеснил бы площадочные баннеры, и узнали бы мы об этом от маркетинга,
 * а не от кода.
 *
 * Порядок склейки (`BannersService.findActive`) такой: первый слот — всегда
 * площадке, следом до `SHOP_BANNER_SLOTS` баннеров продавцов, дальше остаток
 * площадочных, и всё вместе режется по `MAX_ACTIVE_BANNERS`. Первое место
 * оставлено площадке потому, что им распоряжается решение о том, что площадка
 * продвигает прямо сейчас, — акцию, распродажу, запуск раздела. Продавец же
 * покупает не первое место, а гарантированное присутствие в карусели, и второй
 * слот даёт это целиком: он виден тем же движением, что и первый.
 */
export const SHOP_BANNER_SLOTS = 4;

/**
 * Окно ротации баннеров продавцов в секундах — та же пятиминутка, что у
 * продвижения товаров в витрине.
 *
 * Ротация нужна потому, что подписчиков с баннером может оказаться больше, чем
 * мест: фиксированный порядок (по `sort_order` или по дате) означал бы, что
 * пятый и следующие не увидят никогда, заплатив ровно столько же. Окно делает
 * ответ неподвижным внутри пяти минут — без него карусель перетасовывалась бы
 * между серверным рендером главной и гидратацией, и первый кадр страницы
 * дёргался бы на глазах у покупателя.
 */
export const SHOP_BANNER_ROTATION_SEC = 300;

/**
 * Ключ текущего окна ротации — зерно, по которому считается порядок баннеров
 * продавцов.
 *
 * Номер окна, а не его начало в ISO: строка короче, а от зерна нужны ровно два
 * свойства — меняться раз в `SHOP_BANNER_ROTATION_SEC` и быть одинаковым у
 * всех процессов приложения. Отсюда следует обещание: одобренный баннер встаёт
 * в карусель не позже чем через пять минут, и на столько же задерживается его
 * уход после истечения подписки.
 */
export function bucketKey(now: Date = new Date()): string {
  const windowMs = SHOP_BANNER_ROTATION_SEC * 1000;
  return String(Math.floor(now.getTime() / windowMs));
}

/**
 * Статусы модерации баннера. Берутся из самого `pgEnum`, а не объявляются
 * очередным списком тех же трёх слов: список, живущий отдельно от колонки,
 * разъедется с ней в тот день, когда в enum добавят значение.
 */
export const BANNER_MODERATION_STATUSES = moderationStatusEnum.enumValues;
export type BannerModerationStatus =
  (typeof BANNER_MODERATION_STATUSES)[number];

/**
 * Чем модерация может закончиться. Подмножество статусов без `pending`:
 * «вернуть баннер в очередь» — не решение администратора, а следствие правки
 * баннера продавцом, и делает это `updateOwn`. Разрешив `pending` в теле
 * запроса, мы дали бы администратору кнопку, которая ничего не сообщает
 * продавцу и оставляет баннер ровно в том же состоянии.
 */
export const BANNER_MODERATION_DECISIONS = [
  'approved',
  'rejected',
] as const satisfies readonly BannerModerationStatus[];
export type BannerModerationDecision =
  (typeof BANNER_MODERATION_DECISIONS)[number];
