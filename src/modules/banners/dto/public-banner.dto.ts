import { ApiProperty } from '@nestjs/swagger';

/**
 * Баннер как его видит покупатель.
 *
 * Отдельный класс, а не `BannerDto` с необязательными полями, — и это защита,
 * а не аккуратность. С появлением баннеров продавцов в строке завелись поля
 * модерации, среди них `rejectReason`: текст, который администратор пишет
 * продавцу («фотография чужого товара», «текст обрезан»). Публичный ответ
 * главной страницы кэшируется, раздаётся всем и попадает в HTML серверного
 * рендера — утечь туда переписке модератора с продавцом нельзя.
 *
 * Защита двойная и намеренно избыточная: выборка отдаёт явный список колонок
 * (`PUBLIC_COLUMNS`), а тип ответа объявляет ровно то же самое. Одного слоя
 * мало: сериализатор Nest отдаёт то, что вернул сервис, а не то, что описано
 * в DTO, — значит, класс без выборки ничего не гарантирует; выборка же без
 * класса оставила бы Swagger описывать поля, которых в ответе нет.
 *
 * Все три картинки отдаются сразу, а не одна по заголовку Accept-Language:
 * язык на клиенте хранится в localStorage и переключается без перезагрузки,
 * так что выбор картинки — его работа, а ответ остаётся кэшируемым в одном
 * экземпляре.
 */
export class PublicBannerDto {
  @ApiProperty({ example: 1 })
  id: number;

  @ApiProperty({ example: 'Школьный базар — выгода до 50%' })
  title: string;

  @ApiProperty({ format: 'uuid' })
  photoRu: string;

  @ApiProperty({ format: 'uuid' })
  photoUzLatn: string;

  @ApiProperty({ format: 'uuid' })
  photoUzCyrl: string;

  /**
   * `type` указан явно: по объявлению `string | null` рефлексия отдаёт Object,
   * и в спеке поле выходит без типа — на клиенте оно приезжает как `unknown`.
   */
  @ApiProperty({ type: String, nullable: true, example: '/product/12' })
  linkUrl: string | null;
}
