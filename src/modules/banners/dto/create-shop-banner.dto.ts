import { OmitType } from '@nestjs/swagger';
import { CreateBannerDto } from './create-banner.dto';

/**
 * Заявка продавца на баннер.
 *
 * От админского тела отличается ровно двумя отсутствующими полями, и оба
 * убраны не для красоты. `sortOrder` продавцу нечего задавать: порядок
 * баннеров продавцов задаёт ротация, а не число в строке, — приняв его, мы
 * пообещали бы влияние на выдачу, которого нет. `isActive` убран потому, что
 * «выключить» здесь ничего не значит: баннер и так не показывается, пока не
 * одобрен и пока жива подписка, а выключенный баннер в кабинете читался бы как
 * «я его спрятал», хотя прятать нечего.
 *
 * `OmitType`, а не отдельный класс с теми же четырьмя полями: заголовок,
 * картинки и ссылка обязаны валидироваться у продавца ровно так же, как у
 * администратора, — включая шаблон ссылки, который отсекает `javascript:`.
 * Копия разъехалась бы с оригиналом на первой же правке.
 *
 * Попытка всё-таки прислать `isActive` или `sortOrder` вернёт 400 сама:
 * глобальный `forbidNonWhitelisted` отвергает поля, которых нет в DTO. Ловить
 * это в сервисе не нужно и вредно — тихо проигнорированное поле выглядит как
 * принятое.
 */
export class CreateShopBannerDto extends OmitType(CreateBannerDto, [
  'isActive',
  'sortOrder',
] as const) {}
