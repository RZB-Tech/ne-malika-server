import type { Shop } from '../../db/schema';

/**
 * Тарифы подписки: из чего они состоят и как узнать действующий.
 *
 * Файл намеренно ничего не знает про Nest и не объявляет провайдеров. Его
 * читают кредиты, баннеры, витрина товаров и аналитика; импорт
 * `SubscriptionsModule` в каждый из них замкнул бы кольцо — сам модуль
 * подписок зависит от кредитов. Ровно по этой причине SQL-половина тех же
 * правил (`SUBSCRIPTION_ACTIVE`, `AVAILABLE_CREDITS`) лежит отдельным файлом
 * `src/db/subscriptions.ts`, а не в сервисе.
 *
 * Разделение обязанностей внутри файла: цены приходят снаружи, из
 * `ConfigService`, потому что прайс меняется без пересборки образа; всё
 * остальное — кредиты, лимиты, веса, слоты, глубина аналитики — объявлено
 * здесь. Это часть продукта, а не настройка развёртывания: подкрутить норму
 * кредитов переменной окружения на одном стенде значит получить два разных
 * продукта, про которые никто не помнит, чем они различаются.
 */

/**
 * Пояс и календарь площадки. Переэкспорт, а не второе объявление: месяц у
 * площадки один — тот же, по которому режется статистика, — и расхождение
 * двух реализаций стоило бы продавцу бесплатной попытки автозаполнения в ночь
 * на первое число. Разбор — в докблоке `monthStart`.
 */
export { monthStart, TZ } from '../product-stats/product-stats.util';

/**
 * Платные тарифы в порядке возрастания. `free` в список не входит — его нельзя
 * купить, это состояние «подписки нет», а не товар на витрине.
 */
export const PAID_PLANS = ['start', 'pro', 'max'] as const;
export type PaidPlan = (typeof PAID_PLANS)[number];

/**
 * Все значения `shops.subscription_plan`, включая непокупаемый `free`.
 * Выводится из типа строки таблицы, а не объявляется списком: третий список
 * тех же четырёх слов рано или поздно разъедется с `pgEnum`.
 */
export type SubscriptionPlanId = Shop['subscriptionPlan'];

/** Отличает купленный тариф от `free` — нужен там, где план пришёл строкой. */
export function isPaidPlan(value: unknown): value is PaidPlan {
  return (
    typeof value === 'string' &&
    (PAID_PLANS as readonly string[]).includes(value)
  );
}

/**
 * Что тариф даёт магазину. Без цены: цена — это сколько за него просят
 * сегодня, а лимиты — что человек за это получит, и живут они по разным
 * правилам изменения (прайс правится переменной окружения, лимиты — коммитом).
 */
export interface PlanLimits {
  /**
   * Действующий тариф. Именно это поле сравнивают гейты вида «только MAX»
   * (`/searches`, `export.csv`): у истёкшей подписки здесь окажется `free`,
   * тогда как в `shops.subscription_plan` по-прежнему лежит `max`.
   */
  id: SubscriptionPlanId;
  /** Срок в календарных месяцах, покупаемый одной оплатой. */
  months: number;
  /** Подписочные кредиты, выдаваемые при каждой оплате. */
  credits: number;
  /** Бесплатных автозаполнений в календарный месяц. `null` — без лимита. */
  freeAutofills: number | null;
  /**
   * Вес в общей витрине. 1 — как у всех, продвижения нет. Единственное место,
   * где это число живёт вторым экземпляром, — `promoWeightSql` в `ORDER BY`
   * витрины: перебирать тысячи карточек в JS ради веса нельзя, а SQL не умеет
   * читать этот файл. Оба места помечены комментарием друг на друга.
   */
  promoWeight: number;
  /** Сколько баннеров магазину разрешено держать одновременно. */
  bannerSlots: number;
  /** Глубина аналитики в днях. */
  analyticsDays: number;
}

/**
 * Таблица платных тарифов.
 *
 * Записью по идентификатору, а не массивом: почти все обращения — «что даёт
 * вот этот план», и поиск по массиву на каждом гейте пришлось бы либо писать
 * заново, либо оборачивать в ещё одну функцию. Массив нужен ровно одному
 * потребителю — витрине тарифов, и он собирается `buildPlans()`.
 *
 * Числа — решения владельца продукта, а не подобранные значения:
 * START даёт норму кредитов и пять бесплатных автозаполнений, но не двигает
 * магазин в выдаче (вес 1); PRO покупает видимость; MAX добавляет к ней
 * баннер, годовую аналитику и поисковые запросы. Промежуточных сроков нет —
 * везде один месяц.
 */
export const PLAN_LIMITS: Record<PaidPlan, PlanLimits> = {
  start: {
    id: 'start',
    months: 1,
    credits: 3_000,
    freeAutofills: 5,
    promoWeight: 1,
    bannerSlots: 0,
    analyticsDays: 30,
  },
  pro: {
    id: 'pro',
    months: 1,
    credits: 6_000,
    freeAutofills: null,
    promoWeight: 2,
    bannerSlots: 0,
    analyticsDays: 30,
  },
  max: {
    id: 'max',
    months: 1,
    credits: 10_000,
    freeAutofills: null,
    promoWeight: 3,
    bannerSlots: 1,
    analyticsDays: 365,
  },
};

/**
 * Что доступно магазину без действующей подписки.
 *
 * Объявлено явным набором, а не «отсутствием тарифа»: гейты тогда пишутся
 * одинаково для всех — `effectiveLimits(shop).bannerSlots > 0`, — и ни один
 * из них не обязан помнить, что делать с `undefined`. Пропущенная проверка на
 * `undefined` в гейте баннера означала бы баннер бесплатному магазину.
 *
 * `analyticsDays: 30` — не подарок, а сегодняшнее поведение: тридцать дней
 * статистики видит любой продавец и до появления подписок. Отнять их вместе с
 * введением тарифов значило бы обидеть тех, кто ничего не просил (Д4: и не
 * дарим, и не отнимаем). `promoWeight: 1` — та же причина: подписка поднимает
 * подписчика, а не опускает остальных.
 */
export const FREE_LIMITS: PlanLimits = {
  id: 'free',
  months: 0,
  credits: 0,
  freeAutofills: 0,
  promoWeight: 1,
  bannerSlots: 0,
  analyticsDays: 30,
};

/**
 * Действующий тариф магазина — единственная точка, через которую разрешено
 * узнавать, что магазину сейчас положено.
 *
 * **Читать `shop.subscriptionPlan` напрямую запрещено.** Колонка намеренно
 * сохраняет `'max'` после истечения срока: так видно, чем магазин пользовался,
 * и не нужна ночная задача, переводящая просроченных в `free`. Цена этого
 * решения — ровно одна: любая проверка вида `plan === 'max'` выдаёт права
 * магазину, который перестал платить полгода назад. Здесь обе половины
 * условия проверяются вместе и всегда.
 *
 * Условие дословно повторяет `SUBSCRIPTION_ACTIVE` из `src/db/subscriptions.ts`
 * (`plan <> 'free' AND subscription_until > now()`), включая строгость
 * сравнения: срок, истекающий ровно сейчас, уже истёк. Расхождение этих двух
 * выражений дало бы магазину права в одном месте приложения и отказ в другом —
 * самый неприятный вид бага, потому что воспроизводится он одну секунду в
 * месяц.
 *
 * Половину «план не free» проверяем, а не считаем невозможной: инвариант
 * «есть срок → есть платный план» держится кодом, а не базой, и единственная
 * его поломка не должна превращаться в `PLAN_LIMITS['free'] === undefined` и
 * падение на чтении `.bannerSlots`.
 */
export function effectiveLimits(
  shop: Pick<Shop, 'subscriptionPlan' | 'subscriptionUntil'>,
  now: Date = new Date(),
): PlanLimits {
  const until = shop.subscriptionUntil;
  if (!until || until.getTime() <= now.getTime()) return FREE_LIMITS;
  if (!isPaidPlan(shop.subscriptionPlan)) return FREE_LIMITS;
  return PLAN_LIMITS[shop.subscriptionPlan];
}

/** Тариф целиком: лимиты плюс сегодняшняя цена. */
export interface PlanSpec extends PlanLimits {
  id: PaidPlan;
  /** Цена в сумах. */
  priceUzs: number;
}

/**
 * Собрать витрину тарифов, подставив цены из окружения.
 *
 * Функция, а не константа, потому что цены известны только после старта
 * `ConfigService`; собранный массив кладётся в `SubscriptionsService` один раз
 * и дальше только читается.
 *
 * Здесь же — единственная проверка прайса, и она обязана быть именно здесь.
 * Click в колбэке не сообщает, за что заплатили: приходит только сумма, и
 * тариф определяется сопоставлением с прайсом. Две одинаковые цены означают,
 * что сопоставление вернёт первый попавшийся план — то есть человек, купивший
 * MAX, получит PRO, и узнаем мы об этом из жалобы. Ноль или NaN (опечатка в
 * переменной окружения, `parseInt('')`) не совпадёт ни с одной суммой, и
 * тариф не купит никто. Оба случая ловим на старте: упавший при запуске
 * контейнер чинится за минуту, молча сломанный прайс — неделями.
 */
export function buildPlans(prices: Record<PaidPlan, number>): PlanSpec[] {
  const plans = PAID_PLANS.map((id) => ({
    ...PLAN_LIMITS[id],
    id,
    priceUzs: prices[id],
  }));

  for (const plan of plans) {
    if (!Number.isInteger(plan.priceUzs) || plan.priceUzs <= 0) {
      throw new Error(
        `Цена тарифа ${plan.id} задана неверно: ${String(plan.priceUzs)}. ` +
          'Ожидается целое число сумов больше нуля.',
      );
    }
  }

  const distinct = new Set(plans.map((plan) => plan.priceUzs));
  if (distinct.size !== plans.length) {
    throw new Error(
      'Цены тарифов обязаны быть попарно различны: тариф в колбэке Click ' +
        'определяется только по сумме платежа.',
    );
  }

  return plans;
}

/**
 * Сколько бесплатных автозаполнений в месяц даёт START.
 *
 * Выводится из таблицы тарифов, а не объявляется вторым числом: продавцу это
 * число показывает форма товара («осталось 3 из 5»), а расходует его
 * `CreditsService.claimFreeAutofill`, и разъехавшись на единицу они начали бы
 * спорить друг с другом на глазах у покупателя.
 *
 * Живёт здесь, а не в `credits.constants.ts`, потому что это правило тарифа, а
 * не цена операции. `CreditsService` импортирует константу файлом — ровно так
 * `SettingsService` берёт `CREDIT_MARKUP_KEY`, не импортируя `CreditsModule`.
 *
 * `?? 0` недостижим: у START лимит есть. Он стоит потому, что поле общее с PRO
 * и MAX, где `null` означает «без лимита», и молча превратить безлимит в ноль
 * тип обязан запретить.
 */
export const AUTOFILL_FREE_PER_MONTH = PLAN_LIMITS.start.freeAutofills ?? 0;

/**
 * Прибавить месяцы, схлопывая переполнение конца месяца: 31 января плюс месяц
 * даёт 28 (29) февраля, а не 2–3 марта. Без схлопывания оплата 31-го числа
 * дарила бы продавцу лишние сутки каждый короткий месяц, а срок ползал бы
 * вперёд от продления к продлению.
 *
 * На UTC-методах, а не на локальных, как в исходном `addPlanMonths`: контейнер
 * живёт в UTC, `getMonth()/setMonth()` считали бы по поясу процесса, и на
 * машине разработчика в другом поясе граница месяца уехала бы на пять часов —
 * то есть тест, зелёный на сервере, краснел бы локально, и наоборот.
 *
 * Пояс площадки здесь намеренно ни при чём: `subscription_until` — момент
 * времени, а не календарная дата, и продление в середине дня не должно ни
 * отнимать у продавца часы, ни дарить их.
 */
export function addMonths(base: Date, months: number): Date {
  const next = new Date(base);
  const day = next.getUTCDate();
  next.setUTCMonth(next.getUTCMonth() + months);
  if (next.getUTCDate() !== day) next.setUTCDate(0);
  return next;
}

