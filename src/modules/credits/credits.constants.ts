import type { CreditTxnMeta } from '../../db/schema';

/**
 * Кредиты — внутренняя единица расхода на ИИ.
 *
 * 1000 кредитов = $1, который магазин заплатил площадке. Целое число, а не
 * доллары с плавающей точкой: при тысячах мелких списаний доли цента копят
 * ошибку, а сравнение «хватает ли остатка» должно быть точным.
 *
 * Раньше кредит равнялся доллару себестоимости, а наценка вычиталась при
 * начислении: за $20 магазин получал 10 000 кредитов. Считать стало неудобно —
 * баланс не совпадал с деньгами, которые человек отдал. Теперь наоборот:
 * начисляем ровно оплаченное ($20 → 20 000), а наценку берём при списании.
 * Маржа площадки от перестановки не изменилась.
 *
 * Продавцу показываются именно кредиты, а не доллары: так себестоимость
 * запроса и наценка площадки не раскрываются, а множитель можно менять, не
 * объясняясь перед продавцами.
 */
export const CREDITS_PER_USD = 1000;

/** Множитель по умолчанию: расход у OpenRouter стоит магазину вдвое дороже. */
export const DEFAULT_CREDIT_MARKUP = 2;

/** Ключ настройки в app_settings. */
export const CREDIT_MARKUP_KEY = 'credit_markup';

/**
 * Приветственные кредиты: даются магазину один раз, чтобы продавец попробовал
 * генерацию фото, ничего не оплачивая. Начисляются при создании магазина, а
 * тем, кто зарегистрировался раньше, — разово миграциями `0036_welcome_credits`
 * и `0037_welcome_credits_topup`.
 *
 * Сколько это в фото при множителе 2: форма по умолчанию просит две картинки
 * 960×1280 medium и стоит 197 кредитов, одиночное фото — 99, low — 44. То есть
 * 300 хватает на запрос по умолчанию и ещё на одну картинку сверх него.
 *
 * Начинали со 150, но на дефолтных настройках их не хватало даже на первый
 * запрос — подарок упирался в «недостаточно кредитов». Тем, кто успел получить
 * старые 150, миграция 0037 доначисляет разницу.
 */
export const WELCOME_CREDITS = 300;

/** Метка приветственной выдачи в журнале — по ней же ловим повторы. */
export const WELCOME_PROMO = 'welcome';

/** Что продавец увидит в истории кредитов. */
export const WELCOME_NOTE = 'Приветственные кредиты на пробную генерацию';

/**
 * Цена автозаполнения карточки — фиксированная, а не по себестоимости запроса.
 *
 * Остальные операции списывают факт из ответа OpenRouter, и правильно делают:
 * там цена скачет — картинка в high стоит вчетверо дороже low, и брать за них
 * одинаково значило бы либо грабить, либо доплачивать за продавца. Здесь
 * запрос всегда один и тот же: одна модель, до трёх фотографий в `detail: low`
 * и ответ на тысячу токенов, — себестоимость держится около $0.002.
 *
 * За такое фиксированный прайс честнее плавающего: продавец видит цену кнопки
 * до нажатия, а не узнаёт её из истории списаний. Себестоимость при этом всё
 * равно уходит в журнал ИИ (`ai_usage.usd`) — маржа площадки по
 * автозаполнению видна администратору строка за строкой.
 */
export const AUTOFILL_CREDITS = 10;

/**
 * Доллары в кредиты. Всегда вверх: недосписать хуже, чем округлить в свою
 * пользу на десятую долю цента — иначе самые дешёвые запросы (промпт за
 * $0.0003) не стоили бы магазину ничего.
 */
export function usdToCredits(usd: number): number {
  if (!Number.isFinite(usd) || usd <= 0) return 0;
  return Math.ceil(usd * CREDITS_PER_USD);
}

/**
 * Прайс OpenRouter на модели, которыми пользуемся.
 *
 * Нужен только для резерва: списывается всегда фактическая стоимость из ответа.
 * Поэтому неточность прайса не стоит денег — она лишь занимает у магазина
 * чуть больше или чуть меньше кредитов на время запроса.
 *
 * Сверено 13 августа 2026 по openrouter.ai/api/v1/models и
 * /api/v1/images/models/openai/gpt-image-2/endpoints. При смене модели в
 * OPENROUTER_IMAGE_MODEL / OPENROUTER_VISION_MODEL цифры надо обновить.
 */
const IMAGE_OUTPUT_USD_PER_TOKEN = 0.00003;
const IMAGE_INPUT_USD_PER_TOKEN = 0.000008;

/**
 * Сколько токенов на пиксель отдаёт gpt-image-2 по качеству.
 *
 * OpenAI публикует счёт для опорных размеров: 1024×1024 — 272 токена на low,
 * 1056 на medium, 4160 на high. Деление на площадь даёт коэффициент, который
 * сходится и для 1024×1536 (408/1584/6240), поэтому пересчитываем через
 * пиксели: размеров в форме восемь, включая 2880×2880, а таблицей на каждый
 * пришлось бы промахиваться.
 */
const IMAGE_TOKENS_PER_PIXEL: Record<string, number> = {
  low: 272 / (1024 * 1024),
  medium: 1056 / (1024 * 1024),
  high: 4160 / (1024 * 1024),
  /** `auto` модель решает сама — закладываем худший случай. */
  auto: 4160 / (1024 * 1024),
};

/**
 * Запас на одно исходное фото в запросе. Точное число токенов зависит от того,
 * как модель ужмёт картинку, а промахнуться вниз здесь дороже, чем вверх.
 */
const IMAGE_REFERENCE_TOKENS = 1500;

/**
 * Себестоимость пачки картинок в долларах.
 *
 * Именно она, помноженная на наценку, и занимается в резерв. Прежняя оценка
 * шла тирами по стороне картинки и не смотрела на качество — из-за чего
 * high-качество резервировало вчетверо меньше своей цены, а разницу оплачивала
 * площадка.
 */
export function estimateImagesUsd(
  size: string,
  quality: string | undefined,
  count: number,
  references: number,
): number {
  const [width = 0, height = 0] = size
    .split('x')
    .map((n) => Number.parseInt(n, 10) || 0);

  const perPixel =
    IMAGE_TOKENS_PER_PIXEL[quality ?? 'medium'] ??
    IMAGE_TOKENS_PER_PIXEL.medium;

  const outputUsd = width * height * perPixel * IMAGE_OUTPUT_USD_PER_TOKEN;
  const inputUsd =
    Math.max(1, references) *
    IMAGE_REFERENCE_TOKENS *
    IMAGE_INPUT_USD_PER_TOKEN;

  return (outputUsd + inputUsd) * Math.max(1, count);
}

/**
 * Себестоимость промпта по фотографии.
 *
 * Модель зрения дешёвая (gpt-4o-mini: $0.15 за миллион входных токенов и $0.60
 * за миллион выходных), фотографии уходят с `detail: low`. Реальный запрос
 * укладывается в $0.0002–0.0008 — берём верх этой вилки с запасом.
 */
export function estimatePromptUsd(): number {
  return 0.001;
}

/**
 * Как одно списание раскладывается по двум карманам магазина.
 *
 * Отдельным типом, а не парой чисел в сигнатуре: обе половины обязаны быть
 * посчитаны за один раз и от одного и того же остатка, а два отдельных
 * вызова рано или поздно разъехались бы на строке кода между ними.
 */
export interface SpendSplit {
  /** Сколько ушло с подписочного счёта — того, что сгорит при следующей оплате. */
  fromSubscription: number;
  /** Остаток списания, снятый с купленного баланса. Он не сгорает никогда. */
  fromBalance: number;
}

/**
 * Порядок карманов: сперва подписочные кредиты, потом купленные.
 *
 * Правило объявлено здесь и только здесь, отдельной чистой функцией. Причин
 * две. Первая — его нужно проверять тестом: расчёт «сколько из какого кармана»
 * это ровно то место, где ошибка на единицу превращается в чужие деньги, а
 * поднимать ради неё базу с транзакциями невозможно. Вторая — списание живёт
 * внутри `CreditsRepository.spend` между блокировкой строки и апдейтом, и
 * повторить эти три строки где-то ещё будет соблазн ровно до первого
 * расхождения.
 *
 * Почему именно такой порядок: подписочные сгорают при выдаче следующей нормы,
 * купленные не сгорают никогда. Обратный порядок означал бы, что к концу
 * месяца у продавца сгорело ровно то, за что он заплатил отдельно, — и
 * объяснить это ему было бы нечем.
 *
 * `usableSubscription` — уже посчитанный доступный подписочный остаток
 * (`USABLE_SUBSCRIPTION_CREDITS`), а не сырая колонка: у истёкшей подписки он
 * равен нулю, и вся сумма честно уходит с купленного баланса. Проверять срок
 * здесь заново значило бы завести третью копию условия «подписка жива».
 *
 * Отрицательное, дробное и `NaN` схлопываются в ноль вместо того, чтобы
 * протечь в SQL: испорченное число на входе должно стоить магазину ноль
 * кредитов, а не превратиться в `subscription_credits + 12` при вычитании.
 */
export function splitSpend(
  credits: number,
  usableSubscription: number,
): SpendSplit {
  const total = asCount(credits);
  const fromSubscription = Math.min(total, asCount(usableSubscription));
  return { fromSubscription, fromBalance: total - fromSubscription };
}

/** Целое неотрицательное или ноль — деньги дробными и отрицательными не бывают. */
function asCount(value: number): number {
  return Number.isFinite(value) && value > 0 ? Math.floor(value) : 0;
}

/**
 * Чем платится следующее автозаполнение: абонплатой, месячной нормой или
 * кредитами.
 *
 * Функция нужна затем, что этот выбор делается дважды и обязан совпасть:
 * `holdAutofill` по нему решает, что занимать, а `autofillQuota` — что
 * написать на кнопке до нажатия. Разъехавшись, они дали бы худший из
 * возможных багов в деньгах: подпись «бесплатно» над списанием десяти
 * кредитов.
 *
 * На вход идут `PlanLimits` от `effectiveLimits`, а не `shop.subscriptionPlan`
 * (B4): у истёкшей подписки сюда приедет `FREE_LIMITS` с нулём бесплатных
 * попыток, и ветка честно окажется платной.
 *
 * `freeAutofills === null` — безлимит PRO/MAX, и проверять его надо ДО
 * сравнения с потраченным: `null > used` в TypeScript не пишется, а в
 * JavaScript тихо привело бы `null` к нулю и объявило безлимит исчерпанным.
 */
export function autofillCharge(
  limits: { freeAutofills: number | null },
  freeUsedThisMonth: number,
): 'unlimited' | 'free' | 'paid' {
  if (limits.freeAutofills === null) return 'unlimited';
  return asCount(limits.freeAutofills) > asCount(freeUsedThisMonth)
    ? 'free'
    : 'paid';
}

/**
 * Первое число следующего календарного месяца площадки, `YYYY-MM-DD`.
 *
 * Нужно ровно для одного: сказать продавцу, когда обновится норма бесплатных
 * автозаполнений. Считается строкой от строки `monthStart()`, а не
 * арифметикой над `Date`, по той же причине, по которой сам `monthStart`
 * считается поверх `today()`: процесс живёт в UTC, а месяц у площадки
 * ташкентский, и `setMonth` в ночь на первое число вернул бы предыдущий.
 *
 * Отдаётся датой, а не моментом времени, сознательно. Норма сбрасывается в
 * ташкентскую полночь, то есть в 19:00 UTC предыдущих суток; отдав этот момент
 * в ISO, мы получили бы на клиенте «обновится 31 августа» у всякого, чей
 * браузер западнее Ташкента. Дата же читается одинаково везде.
 */
export function nextMonthStart(monthStart: string): string {
  const [year, month] = monthStart.split('-').map(Number);
  if (!year || !month) return monthStart;
  return month === 12
    ? `${year + 1}-01-01`
    : `${year}-${String(month + 1).padStart(2, '0')}-01`;
}

/**
 * Что из подробностей списания видит продавец.
 *
 * Фильтр белым списком, а не удалением лишнего: в `meta` попадает всё, что
 * посчитал нужным записать вызывающий, и «забыть вычеркнуть» новое поле здесь
 * будет ровно один раз — в тот день, когда в журнал добавят ещё одну
 * внутреннюю цифру.
 *
 * Скрывается ровно то, что раскрывает экономику площадки: `usd` —
 * себестоимость запроса у OpenRouter, `paidUsd` и `markup` — сколько магазин
 * заплатил и с каким множителем ему это пересчитали, `estimated` — что
 * стоимость не пришла и списали оценку. Первые три вместе дают маржу площадки
 * с точностью до цента, и объявлять её продавцу мы не собирались: в кредитах
 * он видит цену операции, а не наш прайс у поставщика (см. докблок
 * `CREDITS_PER_USD`). Администратору всё это по-прежнему видно целиком — его
 * история идёт мимо этой функции.
 */
export function sellerVisibleMeta(
  meta: CreditTxnMeta | null,
): CreditTxnMeta | null {
  if (!meta) return null;
  const visible: CreditTxnMeta = {};
  if (meta.operation !== undefined) visible.operation = meta.operation;
  if (meta.images !== undefined) visible.images = meta.images;
  if (meta.promo !== undefined) visible.promo = meta.promo;
  if (meta.plan !== undefined) visible.plan = meta.plan;
  if (meta.fromSubscription !== undefined) {
    visible.fromSubscription = meta.fromSubscription;
  }
  if (meta.free !== undefined) visible.free = meta.free;
  if (meta.fixed !== undefined) visible.fixed = meta.fixed;
  if (meta.paymentId !== undefined) visible.paymentId = meta.paymentId;
  return visible;
}
