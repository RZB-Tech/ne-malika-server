import { sql, type SQL } from 'drizzle-orm';
import { shops } from './schema';

/**
 * Что значит «подписка магазина жива» и сколько кредитов ему сейчас доступно —
 * в одном месте, по образцу `public-products.ts`.
 *
 * Файлом, а не сервисом, намеренно: эти выражения нужны кредитам, баннерам и
 * витрине товаров одновременно, и импорт `SubscriptionsModule` в каждый из них
 * замкнул бы кольцо — сам модуль подписок зависит от кредитов. Файл с чистыми
 * SQL-выражениями зависимостей не имеет и колец не создаёт.
 *
 * Все три выражения написаны поверх колонок `shops`, поэтому пригодны только
 * там, где эта таблица уже в запросе (сама выборка или join).
 */

/**
 * Подписка жива. Обе половины обязательны: `plan <> 'free'` без срока
 * означал бы вечный тариф у всякого, кто когда-то платил, а срок без тарифа —
 * права у магазина, который никогда ничего не покупал.
 */
export const SUBSCRIPTION_ACTIVE: SQL = sql`(${shops.subscriptionPlan} <> 'free' AND ${shops.subscriptionUntil} > now())`;

/**
 * Подписочные кредиты, доступные к трате. Истёкшая подписка их не сжигает —
 * она их запирает: оплатив снова, продавец получит норму тарифа, а не
 * остатки прошлой, но и не обнаружит, что за просрочку у него что-то отняли.
 */
export const USABLE_SUBSCRIPTION_CREDITS: SQL = sql`(case when ${SUBSCRIPTION_ACTIVE} then ${shops.subscriptionCredits} else 0 end)`;

/** Весь доступный магазину остаток: подписочный плюс несгорающий. */
export const AVAILABLE_CREDITS: SQL = sql`(${shops.creditsBalance} + ${USABLE_SUBSCRIPTION_CREDITS} - ${shops.creditsReserved})`;
