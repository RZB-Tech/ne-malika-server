-- Окно тестовой оплаты: разовый пропуск для символической суммы.
--
-- Тариф определяется по сумме платежа — Click не сообщает, за что заплатили, —
-- поэтому «принимать 1000 сум как тест» без всяких условий означало бы
-- принимать её от кого угодно и всегда, то есть открыть подписку по цене
-- в шестьдесят пять раз ниже прайса. Колонка превращает тестовую сумму в
-- разовый пропуск: администратор взводит окно на конкретный магазин, оно живёт
-- полчаса и закрывается на первом же успешном Complete.
--
-- Момент, а не флаг: флаг пришлось бы снимать заданием по расписанию, а
-- забытый взведённым флаг — это и есть та самая дверь. Просроченное окно не
-- требует ничего: сравнение с now() само отвечает «закрыто».
--
-- Отдельной таблицы под это нет намеренно. У магазина не бывает двух окон
-- одновременно, а связь один-к-одному, вынесенная в таблицу, — это лишний
-- join на каждом Prepare ради строки, которой у подавляющего большинства
-- магазинов не существует.
--
-- Индекса нет и не нужно: колонка читается только по уже найденному магазину
-- (Prepare разрешает его по telegram-id владельца), а выборки «все магазины с
-- открытым окном» в коде нет.
ALTER TABLE "shops" ADD COLUMN "subscription_test_until" timestamp with time zone;
