-- Раздел «Сумки и рюкзаки».
--
-- Отдельным корнем, а не подкатегорией ноутбуков: сумку ищут как сумку, и
-- прятать её внутрь «Ноутбуков» значит требовать от покупателя догадки. Рядом
-- в каталоге уже стоят такие же «не комплектующие» — игровые аксессуары и
-- компьютерная мебель, туда же по позиции (230) встаёт и этот раздел.
--
-- Без дробления на подразделы — как «Периферия» и «Корпуса» после последних
-- правок: выбор между рюкзаком и сумкой человек делает глазами по витрине, а
-- не в меню.

INSERT INTO "categories" ("parent_id", "slug", "name_ru", "name_uz_latn", "name_uz_cyrl", "icon", "position") VALUES
  (NULL, 'bags', 'Сумки и рюкзаки', 'Sumka va ryukzaklar', 'Сумка ва рюкзаклар', 'Backpack', 230)
ON CONFLICT DO NOTHING;
