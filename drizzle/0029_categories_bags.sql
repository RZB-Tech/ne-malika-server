-- Товары, которые уже лежат на витрине без категории. Их десяток, и в дерево
-- каталога они сейчас не попадают вовсе — найти их можно только поиском.
--
-- Трогаем ровно те, у кого категории нет: у остальных её выбрал продавец, и
-- переписывать его выбор по совпадению слова в названии нельзя. «Чехол» берём
-- только вместе с ноутбуком — чехлы бывают и у телефонов, и у инструментов.
UPDATE "product_cards"
SET "category_id" = (
      SELECT "id" FROM "categories" WHERE "slug" = 'bags' AND "parent_id" IS NULL
    ),
    "updated_at" = now()
WHERE "category_id" IS NULL
  AND (
    "name" ILIKE '%рюкзак%'
    OR "name" ILIKE '%сумк%'
    OR ("name" ILIKE '%чехол%' AND ("name" ILIKE '%ноут%' OR "name" ILIKE '%macbook%'))
  );
