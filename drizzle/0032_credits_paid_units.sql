-- Кредит теперь равен оплаченному доллару, а не доллару себестоимости.
--
-- Раньше наценка вычиталась при начислении: за $20 магазин получал 10 000
-- кредитов, а списывалась чистая себестоимость запроса. Теперь начисляем
-- ровно оплаченное ($20 → 20 000), а наценку берём при списании. Маржа
-- площадки та же, но баланс наконец совпадает с деньгами, которые человек отдал.
--
-- Балансы, выданные по старым правилам, надо привести к новым единицам —
-- иначе покупательная способность остатка молча упала бы вдвое. Множитель
-- берём из настроек: администратор мог сменить его с двойки.
--
-- Историю в credit_transactions не трогаем: это журнал того, что уже
-- произошло, и переписывать его задним числом нельзя.
UPDATE "shops"
SET "credits_balance" = (round("credits_balance" * m.markup))::bigint,
    "credits_reserved" = (round("credits_reserved" * m.markup))::bigint,
    "updated_at" = now()
FROM (
  SELECT greatest(
    1,
    coalesce(
      (SELECT ("value" #>> '{}')::numeric FROM "app_settings" WHERE "key" = 'credit_markup'),
      2
    )
  ) AS markup
) m
WHERE "credits_balance" > 0 OR "credits_reserved" > 0;
